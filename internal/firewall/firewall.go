// Package firewall 管理入站过滤规则。
//
// 设计要点（PRD §14 S-C01 / ADR-03）：
//   - 优先 nftables，失败降级 iptables-legacy，都不可用则明确报错，不静默失败；
//   - 规则用声明式结构描述，由本包渲染成脚本，不接受用户提供的原始脚本；
//   - SSH 端口与面板端口永远先于用户规则放行，避免一键操作把人锁在门外；
//   - 白名单模式（存在 port="*" 的 drop 规则）才把链尾设为 drop，其余情况保持 accept；
//   - 封禁集合用 nft set 自带 timeout，"封一小时自动解"不需要额外定时任务。
package firewall

import (
	"errors"
	"fmt"
	"net"
	"os"
	"os/exec"
	"regexp"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"time"
	"unicode"
)

// ErrUnsupported 表示当前平台没有可用的防火墙后端。
var ErrUnsupported = errors.New("当前系统没有可用的防火墙后端（需要 Linux + nftables 或 iptables-legacy）")

// Rule 是一条入站规则。
type Rule struct {
	ID      int64  `json:"id"`
	Action  string `json:"action"` // accept | drop
	Proto   string `json:"proto"`  // tcp | udp | any
	Port    string `json:"port"`   // "80" | "8000-8100" | "*" | ""
	Source  string `json:"source"` // 空表示任意；支持单 IP 或 CIDR
	Comment string `json:"comment"`
	Enabled bool   `json:"enabled"`
}

// ApplyOptions 是一次下发所需的全部输入。
type ApplyOptions struct {
	Rules         []Rule
	SSHPorts      []int
	PanelPort     int
	PanelLoopback bool
}

// Status 是后端探测结果。
type Status struct {
	Supported bool       `json:"supported"`
	Backend   string     `json:"backend"` // nft | iptables | none
	Reason    string     `json:"reason,omitempty"`
	Table     string     `json:"table,omitempty"`
	Whitelist bool       `json:"whitelist"`
	Bans      []BanEntry `json:"bans"`
}

// BanEntry 是一条封禁记录。
type BanEntry struct {
	IP      string    `json:"ip"`
	Expires time.Time `json:"expires_at,omitempty"`
	Backend string    `json:"backend"`
}

const (
	tableName  = "panelvps"
	chainName  = "PANELVPS"
	banSet4    = "ban4"
	banSet6    = "ban6"
	banComment = "panelvps-ban"
	persistDir = "/etc/nftables.d"
	persistTo  = "/etc/nftables.d/panelvps.nft"
)

// Detect 探测可用的后端。只做无副作用的探测（建临时表再删）。
func Detect() Status {
	if runtime.GOOS != "linux" {
		return Status{Backend: "none", Reason: "当前系统不是 Linux，防火墙模块仅在服务器上可用"}
	}
	if _, err := exec.LookPath("nft"); err == nil {
		if err := exec.Command("nft", "add", "table", "inet", tableName+"_probe").Run(); err == nil {
			_ = exec.Command("nft", "delete", "table", "inet", tableName+"_probe").Run()
			return Status{Supported: true, Backend: "nft", Table: "inet " + tableName}
		}
	}
	if path, err := exec.LookPath("iptables-legacy"); err == nil {
		if err := exec.Command(path, "-L", "-n").Run(); err == nil {
			return Status{Supported: true, Backend: "iptables", Table: chainName}
		}
	}
	return Status{Backend: "none", Reason: "nft 与 iptables-legacy 都不可用（可能运行在受限容器或非 Linux 内核）"}
}

var (
	portRe   = regexp.MustCompile(`^\d{1,5}(-\d{1,5})?$`)
	ifaceRe  = regexp.MustCompile(`^[A-Za-z0-9_.:@-]{1,32}$`)
	domainRe = regexp.MustCompile(`^[A-Za-z0-9.-]{1,253}$`)
)

// ValidateRule 校验单条规则。渲染前的最后一道闸门。
func ValidateRule(r Rule) error {
	switch r.Action {
	case "accept", "drop":
	default:
		return fmt.Errorf("动作只能是 accept 或 drop，当前为 %q", r.Action)
	}
	switch r.Proto {
	case "tcp", "udp", "any":
	default:
		return fmt.Errorf("协议只能是 tcp/udp/any，当前为 %q", r.Proto)
	}

	p := strings.TrimSpace(r.Port)
	switch p {
	case "", "*":
		// 不限定端口
	default:
		if !portRe.MatchString(p) {
			return fmt.Errorf("端口格式应为 80 或 8000-8100，当前为 %q", p)
		}
		parts := strings.SplitN(p, "-", 2)
		start, _ := strconv.Atoi(parts[0])
		if start < 1 || start > 65535 {
			return fmt.Errorf("端口超出范围: %d", start)
		}
		if len(parts) == 2 {
			end, _ := strconv.Atoi(parts[1])
			if end < start || end > 65535 {
				return fmt.Errorf("端口区间非法: %s", p)
			}
		}
	}

	if s := strings.TrimSpace(r.Source); s != "" {
		if strings.Contains(s, "/") {
			if _, _, err := net.ParseCIDR(s); err != nil {
				return fmt.Errorf("来源网段非法: %q", s)
			}
		} else if net.ParseIP(s) == nil {
			return fmt.Errorf("来源 IP 非法: %q", s)
		}
	}
	if len(r.Comment) > 120 {
		return errors.New("备注过长（最多 120 字节）")
	}
	return nil
}

// isWhitelist 判断是否启用「默认拒绝」：存在启用中的 port="*" drop 规则。
func isWhitelist(rules []Rule) bool {
	for _, r := range rules {
		if r.Enabled && r.Action == "drop" && (r.Port == "*" || r.Port == "") && strings.TrimSpace(r.Source) == "" {
			return true
		}
	}
	return false
}

// Render 渲染 nftables 脚本。导出是为了能在非 Linux 上做单测。
func Render(opt ApplyOptions) (string, error) {
	var b strings.Builder
	wl := isWhitelist(opt.Rules)

	b.WriteString("# generated by PanelVPS — 不要手工编辑，改动会被覆盖\n")
	fmt.Fprintf(&b, "table inet %s {\n", tableName)
	fmt.Fprintf(&b, "  set %s { type ipv4_addr; flags interval; timeout 1h; }\n", banSet4)
	fmt.Fprintf(&b, "  set %s { type ipv6_addr; flags interval; timeout 1h; }\n", banSet6)
	b.WriteString("  chain input {\n")
	b.WriteString("    type filter hook input priority filter; policy accept;\n")
	b.WriteString("    ct state established,related accept\n")
	b.WriteString("    iif \"lo\" accept\n")
	b.WriteString("    ip protocol icmp accept\n")
	b.WriteString("    ip6 nexthdr ipv6-icmp accept\n")

	// 永久放行：SSH 与面板自身端口。顺序在所有用户规则之前。
	for _, port := range dedupPorts(opt.SSHPorts) {
		fmt.Fprintf(&b, "    tcp dport %d accept comment \"ssh (panelvps safety)\"\n", port)
	}
	if opt.PanelPort > 0 && !opt.PanelLoopback {
		fmt.Fprintf(&b, "    tcp dport %d accept comment \"panel (panelvps safety)\"\n", opt.PanelPort)
	}

	// 封禁集合先于业务规则匹配
	fmt.Fprintf(&b, "    ip saddr @%s drop\n", banSet4)
	fmt.Fprintf(&b, "    ip6 saddr @%s drop\n", banSet6)

	accepts, drops := splitRules(opt.Rules)
	for _, r := range accepts {
		b.WriteString("    " + renderRule(r, "accept") + "\n")
	}
	for _, r := range drops {
		// 白名单模式的兜底 drop 在链尾单独处理，这里跳过
		if r.Port == "*" || r.Port == "" {
			if strings.TrimSpace(r.Source) == "" {
				continue
			}
		}
		b.WriteString("    " + renderRule(r, "drop") + "\n")
	}

	if wl {
		b.WriteString("    counter drop comment \"default deny (whitelist mode)\"\n")
	}
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

func splitRules(rules []Rule) (accepts, drops []Rule) {
	for _, r := range rules {
		if !r.Enabled {
			continue
		}
		if err := ValidateRule(r); err != nil {
			continue
		}
		if r.Action == "accept" {
			accepts = append(accepts, r)
		} else {
			drops = append(drops, r)
		}
	}
	// 端口明确的规则排在范围规则前面，读起来更符合直觉
	sort.SliceStable(accepts, func(i, j int) bool { return accepts[i].Port < accepts[j].Port })
	sort.SliceStable(drops, func(i, j int) bool { return drops[i].Port < drops[j].Port })
	return accepts, drops
}

func renderRule(r Rule, verdict string) string {
	var parts []string
	src := strings.TrimSpace(r.Source)
	if src != "" {
		family := "ip"
		if strings.Contains(src, ":") {
			family = "ip6"
		}
		parts = append(parts, fmt.Sprintf("%s saddr %s", family, src))
	}
	hasPort := r.Port != "" && r.Port != "*"
	switch {
	case r.Proto == "tcp" || r.Proto == "udp":
		parts = append(parts, "meta l4proto "+r.Proto)
	case hasPort:
		// 未限定协议但限定了端口：同时匹配 tcp/udp，
		// 否则 nft 会因 th 缺少协议上下文而报错
		parts = append(parts, "meta l4proto { tcp, udp }")
	}
	if hasPort {
		parts = append(parts, "th dport "+r.Port)
	}
	if len(parts) == 0 {
		parts = append(parts, "meta nfproto ipv4")
	}
	line := strings.Join(parts, " ") + " " + verdict
	if r.Comment != "" {
		line += fmt.Sprintf(" comment %q", sanitizeComment(r.Comment))
	}
	return line
}

func sanitizeComment(s string) string {
	s = strings.ReplaceAll(s, `\`, "/")
	s = strings.ReplaceAll(s, `"`, "'")
	s = strings.ReplaceAll(s, "\n", " ")
	if len(s) > 120 {
		s = s[:120]
	}
	return s
}

func dedupPorts(in []int) []int {
	seen := map[int]bool{}
	var out []int
	for _, p := range in {
		if p > 0 && p < 65536 && !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	sort.Ints(out)
	return out
}

// Apply 下发规则。返回实际执行的脚本，便于审计与排错。
func Apply(opt ApplyOptions) (string, error) {
	st := Detect()
	if !st.Supported {
		return "", ErrUnsupported
	}
	for _, r := range opt.Rules {
		if r.Enabled {
			if err := ValidateRule(r); err != nil {
				return "", fmt.Errorf("规则 #%d 非法: %w", r.ID, err)
			}
		}
	}

	switch st.Backend {
	case "nft":
		script, err := Render(opt)
		if err != nil {
			return "", err
		}
		if err := applyNft(script); err != nil {
			return script, err
		}
		// 尽力持久化；失败不回滚已生效的规则，但要告知调用方
		if err := persistNft(script); err != nil {
			return script, fmt.Errorf("规则已生效，但持久化失败（重启后会丢失）: %w", err)
		}
		return script, nil
	case "iptables":
		script, err := renderIptables(opt)
		if err != nil {
			return "", err
		}
		if err := applyIptables(script); err != nil {
			return script, err
		}
		return script, nil
	default:
		return "", ErrUnsupported
	}
}

func applyNft(script string) error {
	tmp, err := os.CreateTemp("", "panelvps-nft-*.nft")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.WriteString(script); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}

	// 先保证表存在，再整体 flush + 重建。flush 只清空本表，不影响系统其他规则。
	if err := exec.Command("nft", "add", "table", "inet", tableName).Run(); err != nil {
		// 表已存在时会报错，忽略；真正的权限问题会在下一步暴露
		_ = err
	}
	flush := exec.Command("nft", "flush", "table", "inet", tableName)
	if out, err := flush.CombinedOutput(); err != nil {
		return fmt.Errorf("清空旧规则失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	out, err := exec.Command("nft", "-f", name).CombinedOutput()
	if err != nil {
		return fmt.Errorf("应用 nftables 规则失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

func persistNft(script string) error {
	if err := os.MkdirAll(persistDir, 0o755); err != nil {
		return err
	}
	body := "# 由 PanelVPS 生成；systemd 启动时由 nftables.service 加载\n" + script
	if err := os.WriteFile(persistTo, []byte(body), 0o644); err != nil {
		return err
	}
	// 确保 /etc/nftables.conf 引用了我们的片段
	const mainConf = "/etc/nftables.conf"
	raw, err := os.ReadFile(mainConf)
	if err != nil {
		if os.IsNotExist(err) {
			return os.WriteFile(mainConf, []byte("#!/usr/sbin/nft -f\nflush ruleset\ninclude \""+persistTo+"\"\n"), 0o644)
		}
		return err
	}
	include := `include "` + persistTo + `"`
	if strings.Contains(string(raw), include) {
		return nil
	}
	f, err := os.OpenFile(mainConf, os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = f.WriteString("\n" + include + "\n")
	return err
}

// ---------- iptables 降级实现 ----------

func renderIptables(opt ApplyOptions) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "%s -N %s 2>/dev/null || true\n", ipt(), chainName)
	fmt.Fprintf(&b, "%s -F %s\n", ipt(), chainName)
	fmt.Fprintf(&b, "%s -A %s -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT\n", ipt(), chainName)
	fmt.Fprintf(&b, "%s -A %s -i lo -j ACCEPT\n", ipt(), chainName)
	fmt.Fprintf(&b, "%s -A %s -p icmp -j ACCEPT\n", ipt(), chainName)

	for _, port := range dedupPorts(opt.SSHPorts) {
		fmt.Fprintf(&b, "%s -A %s -p tcp --dport %d -j ACCEPT -m comment --comment %q\n",
			ipt(), chainName, port, "ssh safety")
	}
	if opt.PanelPort > 0 && !opt.PanelLoopback {
		fmt.Fprintf(&b, "%s -A %s -p tcp --dport %d -j ACCEPT -m comment --comment %q\n",
			ipt(), chainName, opt.PanelPort, "panel safety")
	}

	accepts, drops := splitRules(opt.Rules)
	for _, r := range accepts {
		for _, line := range iptRuleLines(r, "ACCEPT") {
			fmt.Fprintf(&b, "%s -A %s %s\n", ipt(), chainName, line)
		}
	}
	for _, r := range drops {
		if (r.Port == "*" || r.Port == "") && strings.TrimSpace(r.Source) == "" {
			continue
		}
		for _, line := range iptRuleLines(r, "DROP") {
			fmt.Fprintf(&b, "%s -A %s %s\n", ipt(), chainName, line)
		}
	}
	if isWhitelist(opt.Rules) {
		fmt.Fprintf(&b, "%s -A %s -j DROP\n", ipt(), chainName)
	} else {
		fmt.Fprintf(&b, "%s -A %s -j RETURN\n", ipt(), chainName)
	}
	fmt.Fprintf(&b, "%s -C INPUT -j %s 2>/dev/null || %s -I INPUT -j %s\n", ipt(), chainName, ipt(), chainName)
	return b.String(), nil
}

func ipt() string { return "iptables-legacy" }

// iptRuleLines 生成一条或多条 iptables 参数串。
//
// 未指定协议却指定端口时必须拆成 tcp/udp 两条，因为 iptables 的 --dport
// 依赖 -p 提供的协议上下文。
func iptRuleLines(r Rule, verdict string) []string {
	var common []string
	if s := strings.TrimSpace(r.Source); s != "" {
		common = append(common, "-s "+s)
	}
	if r.Comment != "" {
		common = append(common, fmt.Sprintf("-m comment --comment %q", shellSafe(r.Comment)))
	}

	hasPort := r.Port != "" && r.Port != "*"
	var protos []string
	switch {
	case r.Proto == "tcp" || r.Proto == "udp":
		protos = []string{r.Proto}
	case hasPort:
		protos = []string{"tcp", "udp"}
	}

	if len(protos) == 0 {
		parts := append([]string{}, common...)
		parts = append(parts, "-j "+verdict)
		return []string{strings.Join(parts, " ")}
	}

	var out []string
	for _, p := range protos {
		parts := []string{"-p " + p}
		if hasPort {
			parts = append(parts, "--dport "+r.Port)
		}
		parts = append(parts, common...)
		parts = append(parts, "-j "+verdict)
		out = append(out, strings.Join(parts, " "))
	}
	return out
}

// shellSafe 把备注收敛到「字母/数字/空格/._-」。
//
// iptables 降级路径必须经过 sh -c，而备注是用户输入；不这样处理，
// 一个带 $(...) 的备注就能变成任意命令执行。
func shellSafe(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case unicode.IsLetter(r), unicode.IsDigit(r), r == ' ', r == '.', r == '_', r == '-':
			b.WriteRune(r)
		}
	}
	out := strings.TrimSpace(b.String())
	if out == "" {
		return "panelvps rule"
	}
	if len(out) > 100 {
		out = out[:100]
	}
	return out
}

// applyIptables 逐条执行生成的命令。这里必须走 shell，因为脚本里有 || 逻辑；
// 脚本内容完全由本包生成，所有用户输入都经过 ValidateRule 与正则校验。
func applyIptables(script string) error {
	for _, line := range strings.Split(script, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		cmd := exec.Command("sh", "-c", line)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("执行 %q 失败: %v %s", line, err, strings.TrimSpace(string(out)))
		}
	}
	return nil
}

// ---------- 封禁集合 ----------

// EnsureBase 确保表与封禁集合存在，供封禁接口单独调用。
func EnsureBase() error {
	st := Detect()
	if !st.Supported {
		return ErrUnsupported
	}
	if st.Backend != "nft" {
		return nil // iptables 模式不需要预建集合
	}
	if err := exec.Command("nft", "add", "table", "inet", tableName).Run(); err != nil {
		// 已存在
		_ = err
	}
	for _, s := range []struct{ name, typ string }{{banSet4, "ipv4_addr"}, {banSet6, "ipv6_addr"}} {
		_ = exec.Command("nft", "add", "set", "inet", tableName, s.name,
			"{ type "+s.typ+"; flags interval; timeout 1h; }").Run()
	}
	return nil
}

// Ban 把 IP 加入封禁集合。nft 模式下由内核自动到期。
func Ban(ip string, ttl time.Duration) error {
	parsed := net.ParseIP(strings.TrimSpace(ip))
	if parsed == nil {
		return fmt.Errorf("IP 非法: %q", ip)
	}
	st := Detect()
	if !st.Supported {
		return ErrUnsupported
	}
	if ttl < time.Minute {
		ttl = time.Minute
	}
	if ttl > 30*24*time.Hour {
		ttl = 30 * 24 * time.Hour
	}
	if st.Backend == "nft" {
		if err := EnsureBase(); err != nil {
			return err
		}
		set := banSet4
		if parsed.To4() == nil {
			set = banSet6
		}
		spec := fmt.Sprintf("{ %s timeout %s }", parsed.String(), ttl.String())
		out, err := exec.Command("nft", "add", "element", "inet", tableName, set, spec).CombinedOutput()
		if err != nil {
			// 已存在时 nft 会报 File exists，视为成功
			if strings.Contains(string(out), "File exists") {
				return nil
			}
			return fmt.Errorf("封禁失败: %v %s", err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	// iptables 模式：插入带注释的 DROP 规则，由后台清理任务负责到期删除
	args := []string{"-I", "INPUT", "-s", parsed.String(), "-j", "DROP",
		"-m", "comment", "--comment", banComment}
	if out, err := exec.Command(ipt(), args...).CombinedOutput(); err != nil {
		return fmt.Errorf("封禁失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Unban 解除封禁。
func Unban(ip string) error {
	parsed := net.ParseIP(strings.TrimSpace(ip))
	if parsed == nil {
		return fmt.Errorf("IP 非法: %q", ip)
	}
	st := Detect()
	if !st.Supported {
		return ErrUnsupported
	}
	if st.Backend == "nft" {
		set := banSet4
		if parsed.To4() == nil {
			set = banSet6
		}
		out, err := exec.Command("nft", "delete", "element", "inet", tableName, set,
			fmt.Sprintf("{ %s }", parsed.String())).CombinedOutput()
		if err != nil && !strings.Contains(string(out), "No such file") {
			return fmt.Errorf("解封失败: %v %s", err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	out, err := exec.Command(ipt(), "-D", "INPUT", "-s", parsed.String(), "-j", "DROP",
		"-m", "comment", "--comment", banComment).CombinedOutput()
	if err != nil && !strings.Contains(string(out), "does a matching rule exist") {
		return fmt.Errorf("解封失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// ListBans 返回当前封禁列表。
func ListBans() ([]BanEntry, error) {
	st := Detect()
	if !st.Supported {
		return nil, ErrUnsupported
	}
	if st.Backend == "nft" {
		return listNftBans()
	}
	return listIptablesBans()
}

func listNftBans() ([]BanEntry, error) {
	now := time.Now()
	var out []BanEntry
	for _, s := range []struct{ set, backend string }{{banSet4, "nft"}, {banSet6, "nft"}} {
		raw, err := exec.Command("nft", "list", "set", "inet", tableName, s.set).Output()
		if err != nil {
			continue // 集合不存在视为无封禁
		}
		text := string(raw)
		start := strings.Index(text, "elements = {")
		if start < 0 {
			continue
		}
		body := text[start+len("elements = {"):]
		if end := strings.Index(body, "}"); end >= 0 {
			body = body[:end]
		}
		for _, item := range strings.Split(body, ",") {
			fields := strings.Fields(strings.TrimSpace(item))
			if len(fields) == 0 || net.ParseIP(fields[0]) == nil {
				continue
			}
			ban := BanEntry{IP: fields[0], Backend: s.backend}
			for i := 1; i+1 < len(fields); i++ {
				if fields[i] == "expires" {
					if d, err := time.ParseDuration(fields[i+1]); err == nil {
						ban.Expires = now.Add(d)
					}
				}
			}
			out = append(out, ban)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].IP < out[j].IP })
	return out, nil
}

func listIptablesBans() ([]BanEntry, error) {
	raw, err := exec.Command(ipt(), "-S", "INPUT").Output()
	if err != nil {
		return nil, err
	}
	var out []BanEntry
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.Contains(line, banComment) {
			continue
		}
		fields := strings.Fields(line)
		for i := 0; i+1 < len(fields); i++ {
			if fields[i] == "-s" && net.ParseIP(fields[i+1]) != nil {
				out = append(out, BanEntry{IP: fields[i+1], Backend: "iptables"})
				break
			}
		}
	}
	return out, nil
}

// PersistPath 返回规则持久化文件路径，便于前端展示与排错。
func PersistPath() string { return persistTo }

// InterfaceBelongsTo 判断网卡名是否合法，供未来按网卡限速使用。
func InterfaceBelongsTo(name string) bool { return ifaceRe.MatchString(name) }

// DomainLooksValid 供上层校验域名（与站点模块共用一套规则）。
func DomainLooksValid(domain string) bool {
	if !domainRe.MatchString(domain) || strings.HasPrefix(domain, "-") || strings.HasSuffix(domain, "-") {
		return false
	}
	for _, part := range strings.Split(domain, ".") {
		if part == "" || len(part) > 63 || strings.HasPrefix(part, "-") || strings.HasSuffix(part, "-") {
			return false
		}
	}
	return true
}
